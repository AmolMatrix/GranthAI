def _indexed_text(record):
    """Build searchable text while retaining human-readable field labels."""
    fields = (
        ('Title', record['title']), ('Author', record['author']),
        ('Department', record['department']), ('Core concepts', record['concepts']),
        ('Chapter map', record['chapter_map']), ('Subtopics and alternate terms', record['alternate_terms']),
        ('Learning outcomes', record['learning_outcomes']),
        ('Prerequisites', record['prerequisites']), ('Applications', record['applications']),
    )
    return '\n'.join(f'{label}: {value}' for label, value in fields)

def seed_if_empty():
    # Keep existing student/librarian accounts. Replace only the old demo
    # catalog when it is not the requested 50-item curated catalog.
    existing = Book.query.count()
    first = Book.query.order_by(Book.id.asc()).first()
    if existing == 50 and first and first.title == CATALOG[0]['title']:
        return
    if existing:
        # Remove dependent circulation rows before replacing the old sample catalog.
        Reservation.query.delete(synchronize_session=False)
        IssueRecord.query.delete(synchronize_session=False)
        Book.query.delete(synchronize_session=False)
        db.session.flush()

    for index, record in enumerate(CATALOG, start=1):
        db.session.add(Book(
            title=record['title'], author=record['author'],
            department=record['department'], level=record['level'],
            item_type='book', content=_indexed_text(record),
            total_copies=2, available_copies=2,
            shelf_location=f"Rack {record['department'][0]}, Shelf {((index - 1) % 5) + 1}",
            view_count=0,
        ))

    if not User.query.filter_by(email='librarian@granthai.edu').first():
        db.session.add(User(name='Chief Librarian', email='librarian@granthai.edu',
            password_hash=generate_password_hash('librarian123'), role='librarian'))
    if not User.query.filter_by(email='demo.student@gmail.com').first():
        db.session.add(User(name='Demo Student', email='demo.student@gmail.com',
            password_hash=generate_password_hash('student123'), role='student',
            department='Computer Engineering'))
    db.session.commit()
    print(f'Granth AI catalog ready: {len(CATALOG)} indexed books.')
